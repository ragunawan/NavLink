import {expect,test} from '@playwright/test'

test.skip(!process.env.NAVYLINK_SAMPLE_TEST, 'Run explicitly against the loaded sample catalog')

test('loaded sample catalog counts, pagination and filter reset are complete',async({page,request})=>{
  await page.goto('/')
  await expect(page.getByRole('navigation',{name:'Catalog overview'}).locator('a[href="/catalog"] .discovery-value')).toHaveText('500')
  await page.goto('/catalog')
  await expect(page.locator('.results-heading')).toContainText('500 capabilities')
  await expect(page.locator('.project-card')).toHaveCount(50)
  await expect(page.getByRole('button',{name:'Previous page'})).toBeDisabled()
  const first=await page.locator('.project-card h3 a').first().getAttribute('href')
  await page.getByRole('button',{name:'Next page'}).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.getByRole('navigation',{name:'Catalog pages'})).toContainText('Page 2 of 10')
  await expect(page.locator('.project-card h3 a').first()).not.toHaveAttribute('href',first!)
  await page.goto('/catalog?page=10')
  await expect(page.getByRole('navigation',{name:'Catalog pages'})).toContainText('Page 10 of 10')
  await expect(page.locator('.project-card')).toHaveCount(50)
  await expect(page.getByRole('button',{name:'Next page'})).toBeDisabled()
  await page.getByRole('combobox',{name:'Mission domain',exact:true}).selectOption('Maintenance')
  await expect(page).not.toHaveURL(/page=/)
  const filtered=await (await request.get('/api/v1/projects/page?domain=Maintenance')).json()
  await expect(page.locator('.results-heading')).toContainText(`${filtered.total} capabilities`)
  await expect(page.locator('.project-card')).toHaveCount(Math.min(50,filtered.total))
  for(const card of await page.locator('.project-card .tags').all())await expect(card).toContainText('Maintenance')
})

test('sample project links personnel and datasources and omits removed fields',async({page,request})=>{
  const projectId='5bb2b39e-69a2-53a0-9033-08d818778422'
  const project=await (await request.get('/api/v1/projects/'+projectId)).json()
  expect(project).not.toHaveProperty('tags')
  expect(project).not.toHaveProperty('files')
  await page.goto('/projects/'+projectId)
  await expect(page.getByRole('heading',{name:'CASREP Field Dictionary and Example Forms',exact:true})).toBeVisible()
  const metadata=page.locator('.project-metadata')
  await expect(metadata).toContainText('2025-10-08')
  await expect(metadata).toContainText('2026-03-29')
  await expect(metadata).toContainText('hayden.chung.094@navylink-demo.example')
  await expect(metadata).toContainText('Primary POC')
  await expect(page.getByRole('heading',{name:/Keywords|Related files/})).toHaveCount(0)
  await metadata.getByRole('link',{name:'CASREP Documentation Examples',exact:true}).click()
  await expect(page.locator('.record-card')).toHaveCount(1)
  await expect(page.locator('.record-card')).toContainText('CASREP Documentation Examples')
  await page.goto('/people')
  await expect(page.locator('.record-count')).toContainText('176')
  await page.getByRole('textbox',{name:'Search personnel'}).fill('hayden.chung.094@navylink-demo.example')
  await expect(page.locator('.record-card')).toHaveCount(1)
  await page.goto('/datasources')
  await expect(page.locator('.record-count')).toContainText('120')
  await page.goto('/catalog?q=CASREP%20field%20dictionary')
  await expect(page.locator('.project-card h3 a').filter({hasText:'CASREP Field Dictionary and Example Forms'})).toBeVisible()
  await page.goto('/projects/'+projectId+'/edit')
  await page.getByLabel('Demo identity').selectOption('curator')
  await expect(page.getByRole('textbox',{name:'Project name',exact:true})).toHaveValue(project.name)
  await expect(page.getByRole('combobox',{name:/Team lead \/ primary POC/})).toHaveValue(project.primary_poc_email)
  await expect(page.getByRole('textbox',{name:/Keywords|File name|Hosted file URL/})).toHaveCount(0)
  await page.setViewportSize({width:390,height:844})
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390)
})
