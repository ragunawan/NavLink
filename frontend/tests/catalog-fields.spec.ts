import {expect,test} from '@playwright/test'

test('personnel and datasource registries create, edit and protect project references',async({page,request})=>{
  await page.goto('/people')
  await expect(page.getByRole('heading',{name:'Personnel registry'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Add person'})).toHaveCount(0)
  await page.getByLabel('Demo identity').selectOption('curator')
  await page.getByRole('button',{name:'Add person'}).click()
  const person=page.getByRole('form',{name:'Personnel record'})
  await person.getByRole('textbox',{name:'Email',exact:true}).fill('browser.field@navylink.example')
  await person.getByRole('textbox',{name:'Full name',exact:true}).fill('Fictional Browser Field Reviewer')
  await person.getByRole('textbox',{name:'Organization',exact:true}).fill('Fictional Field Lab')
  await person.getByRole('textbox',{name:'Job title',exact:true}).fill('Data Engineer')
  await person.getByRole('textbox',{name:/Work phone/}).fill('555-0123')
  await person.getByRole('textbox',{name:/Areas of expertise/}).fill('AI/ML, Logistics')
  await person.getByRole('button',{name:'Save person',exact:true}).click()
  await page.getByRole('textbox',{name:'Search personnel'}).fill('browser.field@navylink.example')
  const personCard=page.locator('.record-card').filter({hasText:'browser.field@navylink.example'})
  await expect(personCard).toContainText('555-0123')
  await expect(personCard).toContainText('AI/ML')
  await personCard.getByRole('button',{name:'Edit',exact:true}).click()
  await expect(person.getByRole('textbox',{name:'Email',exact:true})).toBeDisabled()
  await person.getByRole('textbox',{name:'Job title',exact:true}).fill('Lead Data Engineer')
  await person.getByRole('button',{name:'Save person',exact:true}).click()
  await expect(personCard).toContainText('Lead Data Engineer')

  await page.getByRole('navigation',{name:'People and data'}).getByRole('link',{name:'Datasources',exact:true}).click()
  await page.getByRole('button',{name:'Add datasource',exact:true}).click()
  const source=page.getByRole('form',{name:'Datasource record'})
  await source.getByRole('textbox',{name:'Datasource name',exact:true}).fill('Fictional Browser CSV Source')
  await source.getByRole('textbox',{name:'Owning organization',exact:true}).fill('Fictional Field Lab')
  await source.getByRole('combobox',{name:'Mission domain',exact:true}).selectOption('Other')
  await source.getByRole('textbox',{name:'Datasource description',exact:true}).fill('Fabricated CSV data for a browser verification.')
  await source.getByRole('button',{name:'Save datasource',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Fictional Browser CSV Source',exact:true})).toBeVisible()

  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Register project',exact:true}).click()
  await expect(page.getByRole('textbox',{name:/Keywords|Hosted file URL/})).toHaveCount(0)
  await page.getByRole('textbox',{name:'Project name',exact:true}).fill('Fictional Catalog Field Capability')
  await page.getByRole('textbox',{name:'Fictional owning organization',exact:true}).fill('Fictional Field Lab')
  await page.getByRole('combobox',{name:'Project type',exact:true}).selectOption('Documentation')
  await page.getByRole('combobox',{name:'Mission domain',exact:true}).selectOption('Other')
  await page.getByRole('textbox',{name:'Mission problem',exact:true}).fill('Coordinate shared synthetic logistics documentation.')
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('A fictional capability to verify documented catalog metadata end to end.')
  await page.getByRole('textbox',{name:/Classification/}).fill('UNCLASSIFIED')
  await page.getByRole('combobox',{name:/Team lead \/ primary POC/}).selectOption('browser.field@navylink.example')
  await page.getByRole('checkbox',{name:'NMCI',exact:true}).check()
  await page.getByRole('checkbox',{name:'CANES',exact:true}).check()
  await page.getByRole('group',{name:'Team members · optional'}).getByRole('checkbox',{name:/maint.2@navylink.example/}).check()
  await page.getByRole('textbox',{name:/Sponsors/}).fill('Fictional Sponsor A, Fictional Sponsor B')
  await page.getByRole('combobox',{name:/^Datasource/}).selectOption('Fictional Browser CSV Source')
  await page.getByRole('textbox',{name:/Project URL/}).fill('https://projects.navylink.example/field-capability')
  await page.getByRole('button',{name:'Check for existing capabilities'}).click()
  await page.getByRole('button',{name:'Save project',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Fictional Catalog Field Capability',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:/Keywords|Related files/})).toHaveCount(0)
  const projectUrl=page.url()
  const id=new URL(projectUrl).pathname.split('/').at(-1)!
  const metadata=page.locator('.project-metadata')
  await expect(metadata).toContainText('UNCLASSIFIED')
  await expect(metadata).toContainText('NMCI, CANES')
  await expect(metadata).toContainText('Fictional Sponsor A, Fictional Sponsor B')
  await expect(metadata).toContainText('Lead Data Engineer')
  await expect(metadata).toContainText('Primary POC')
  await metadata.getByRole('link',{name:'Fictional Browser CSV Source'}).click()
  const sourceCard=page.locator('.record-card').filter({has:page.getByRole('heading',{name:'Fictional Browser CSV Source',exact:true})})
  await sourceCard.getByRole('button',{name:'Delete',exact:true}).click()
  await sourceCard.getByRole('button',{name:'Confirm delete',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('referenced by catalog projects')

  await page.goto(projectUrl)
  await page.getByLabel('Demo identity').selectOption('curator')
  await page.getByRole('link',{name:'Edit project',exact:true}).click()
  await expect(page.getByRole('textbox',{name:/Classification/})).toHaveValue('UNCLASSIFIED')
  await page.getByRole('textbox',{name:/Sponsors/}).fill('Updated Fictional Sponsor')
  await page.getByRole('button',{name:'Check for existing capabilities'}).click()
  await page.getByRole('button',{name:'Save project',exact:true}).click()
  await expect(metadata).toContainText('Updated Fictional Sponsor')

  expect((await request.delete('/api/v1/projects/'+id,{headers:{'X-Demo-User':'curator'}})).ok()).toBeTruthy()
  expect((await request.delete('/api/v1/people/browser.field@navylink.example',{headers:{'X-Demo-User':'curator'}})).ok()).toBeTruthy()
  expect((await request.delete('/api/v1/datasources/Fictional%20Browser%20CSV%20Source',{headers:{'X-Demo-User':'curator'}})).ok()).toBeTruthy()
})

test('record registries are responsive and hide restricted people after identity changes',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/people')
  await page.getByRole('textbox',{name:'Search personnel'}).fill('maint.7@navylink.example')
  await expect(page.getByRole('heading',{name:'No matching records'})).toBeVisible()
  await page.getByLabel('Demo identity').selectOption('maintainer')
  await expect(page.locator('.record-card')).toHaveCount(1)
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390)
  await page.getByLabel('Demo identity').selectOption('visitor')
  await expect(page.getByRole('heading',{name:'No matching records'})).toBeVisible()
  await page.getByRole('navigation',{name:'People and data'}).getByRole('link',{name:'Datasources',exact:true}).click()
  await expect(page.locator('.record-card').first()).toBeVisible()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390)
})
