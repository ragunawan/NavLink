import {expect,test} from '@playwright/test'

test('description-only proposal, reviewed metadata suggestions, collaboration and real relationships',async({page})=>{
  await page.goto('/check')
  await page.getByLabel('Proposed project name',{exact:false}).fill('Fictional Phase 2 Readiness')
  await page.getByLabel('Project description',{exact:false}).fill('Build a Python predictive maintenance platform using Maintenance work orders and Supply inventory to forecast equipment failures and readiness.')
  await page.getByRole('button',{name:'Suggest metadata',exact:true}).click()
  await expect(page.getByLabel('Suggested domain')).toHaveValue('Maintenance')
  await expect(page.getByRole('button',{name:'Apply reviewed suggestions'})).toBeDisabled()
  await page.getByLabel('Suggested technologies').fill('Python, React')
  await page.getByLabel('I reviewed these editable suggestions').check()
  await page.getByRole('button',{name:'Apply reviewed suggestions'}).click()
  await expect(page.getByLabel('Technology stack',{exact:false})).toHaveValue('Python, React')
  await page.getByRole('button',{name:'Analyze Proposal',exact:true}).click()
  await expect(page.getByText('Workflow complete')).toBeVisible()
  await expect(page.getByRole('region',{name:'Collaboration opportunities'})).toContainText('Fictional')
  await expect(page.locator('.candidate')).toHaveCount(5)
  await expect(page.locator('.relationship-label').first()).toContainText('Potential Duplicate')
  await page.locator('.candidate').first().getByText('Similarity components and key differences').click()
  await expect(page.locator('.candidate').first()).toContainText('not a duplicate probability')
  await expect(page.getByRole('table')).toContainText('Intended users')
  await page.screenshot({path:'../docs/phase2-proposal.png',fullPage:true})
})

test('assistant answers, citations and two-project comparison work with external HTTP blocked',async({page})=>{
  const external:string[]=[]
  await page.route('**/*',route=>{const url=new URL(route.request().url());if(!['localhost','127.0.0.1'].includes(url.hostname)){external.push(url.href);return route.abort()}return route.continue()})
  await page.goto('/assistant')
  await page.getByRole('button',{name:'Are there any financial management dashboards?',exact:true}).click()
  await page.getByLabel('Use deterministic answers only').check()
  await page.getByRole('button',{name:'Ask the catalog'}).click()
  const region=page.getByRole('region',{name:'Grounded assistant answer'})
  await expect(region).toContainText('Deterministic · no LLM used')
  await expect(region).toContainText('Budget Compass')
  await expect(region.locator('.answer-facts a').first()).toHaveAttribute('href',/\/projects\/fin-/)
  const sourceHref=await region.locator('.answer-facts a').first().getAttribute('href')
  if(!sourceHref)throw new Error('Expected real citation')
  await region.locator('.answer-facts a').first().click()
  await expect(page).toHaveURL(new RegExp(sourceHref+'$'))
  await page.goto('/assistant')
  await page.getByRole('button',{name:'What are the differences between Keel Prognostics and BearingWatch?',exact:true}).click()
  await page.getByRole('button',{name:'Ask the catalog'}).click()
  await expect(page.getByRole('table',{name:'Side-by-side project comparison'})).toContainText('BearingWatch')
  expect(external).toEqual([])
  await page.screenshot({path:'../docs/assistant.png',fullPage:true})
})

test('RAG identity changes remove restricted evidence and stale suggestions need review',async({page})=>{
  await page.goto('/assistant')
  await page.getByLabel('Demo identity').selectOption('maintainer')
  await page.getByLabel('Your discovery question').fill('Describe Acoustic Health Kit')
  await page.getByRole('button',{name:'Ask the catalog'}).click()
  await expect(page.getByRole('region',{name:'Grounded assistant answer'})).toContainText('Acoustic Health Kit')
  await page.getByLabel('Demo identity').selectOption('visitor')
  await expect(page.getByRole('region',{name:'Grounded assistant answer'})).toHaveCount(0)
  await page.getByLabel('Your discovery question').fill('Describe Acoustic Health Kit')
  await page.getByRole('button',{name:'Ask the catalog'}).click()
  await expect(page.getByRole('region',{name:'Grounded assistant answer'})).not.toContainText('Acoustic Health Kit')
  await page.goto('/check')
  await page.getByLabel('Project description',{exact:false}).fill('Build a financial dashboard with Python and budget execution ledger data.')
  await page.getByRole('button',{name:'Suggest metadata',exact:true}).click()
  await page.getByLabel('I reviewed these editable suggestions').check()
  await page.getByLabel('Project description',{exact:false}).fill('Build a different maintenance planning application using equipment failure data.')
  await expect(page.getByRole('button',{name:'Apply reviewed suggestions'})).toBeDisabled()
  await expect(page.getByText('Description changed; refresh suggestions before applying.')).toBeVisible()
})
