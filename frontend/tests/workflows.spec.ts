test('mobile navigation and local discovery with all external HTTP blocked',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 const external:string[]=[]
 await page.route('**/*',route=>{const url=new URL(route.request().url());if(!['127.0.0.1','localhost'].includes(url.hostname)){external.push(url.href);return route.abort()}return route.continue()})
 await page.goto('/')
 await expect(page.getByRole('navigation',{name:'Catalog overview'}).locator('a[href="/catalog"] .discovery-value')).toHaveText('42')
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390)
 await page.screenshot({path:'../docs/mobile.png',fullPage:true})
 await page.getByRole('button',{name:'Toggle navigation'}).click()
 await page.getByRole('link',{name:'Discover capabilities',exact:true}).click()
 await page.getByRole('textbox',{name:'Search capabilities'}).fill('financial datasets')
 await page.getByRole('button',{name:'Search',exact:true}).click()
 await expect(page.locator('.project-card').first()).toBeVisible()
 expect(external).toEqual([])
 await page.goto('/check')
 await page.getByRole('button',{name:'Predictive maintenance',exact:true}).click()
 await page.getByRole('button',{name:'Analyze Proposal'}).click()
 await expect(page.getByRole('heading',{name:'Recommended path'})).toBeVisible()
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390)
 expect(external).toEqual([])
})
