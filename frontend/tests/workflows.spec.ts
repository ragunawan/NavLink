test('advisor constraints, selectable comparison, citation navigation and saved-run reload',async({page})=>{
 await page.goto('/check')
 await page.getByRole('button',{name:'Predictive maintenance',exact:true}).click()
 await page.getByLabel('Technology stack',{exact:false}).fill('Python, React')
 await page.getByRole('button',{name:'Analyze Proposal'}).click()
 await expect(page.getByText('Workflow complete')).toBeVisible()
 await expect(page).toHaveURL(/check\?run=/)
 const saved=page.url()
 const bearing=page.locator('.candidate').filter({has:page.getByRole('heading',{name:'BearingWatch'})})
 await bearing.getByText('Reuse constraints (8)',{exact:true}).click()
 await expect(bearing.locator('.constraint').filter({has:page.getByText('Licensing',{exact:true})})).toContainText('unknown')
 await expect(bearing.locator('.constraint').filter({has:page.getByText('Technology',{exact:true})})).toContainText('potential mismatch')
 const chooser=page.getByLabel('Comparison project 1',{exact:true})
 const other=await page.getByLabel('Comparison project 2',{exact:true}).inputValue()
 const option=await chooser.locator('option').evaluateAll((options,otherId)=>options.map(o=>({id:(o as HTMLOptionElement).value,label:o.textContent||''})).find(o=>o.id!==otherId),other)
 if(!option)throw new Error('Expected at least two comparison candidates')
 await chooser.selectOption(option.id)
 await expect(page.getByRole('table').locator('thead')).toContainText(option.label)
 const source=page.getByRole('region',{name:'Grounded recommendation'}).getByRole('link').first()
 const name=await source.innerText()
 await source.click()
 await expect(page.getByRole('heading',{name:name.trim(),exact:true})).toBeVisible()
 await page.goto(saved)
 await expect(page.getByRole('heading',{name:'Recommended path'})).toBeVisible()
 await expect(page.getByRole('textbox',{name:'What mission problem are you solving?'})).toHaveValue(/predictive maintenance/)
 await page.reload()
 await expect(page.getByText('Workflow complete')).toBeVisible()
 await page.getByLabel('Demo identity').selectOption('analyst')
 await expect(page.getByRole('alert')).toHaveText('Run not found')
 await expect(page.getByRole('region',{name:'Grounded recommendation'})).toHaveCount(0)
})

